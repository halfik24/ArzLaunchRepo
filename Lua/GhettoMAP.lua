require 'lib.moonloader'
local imgui = require 'mimgui'

local state = imgui.new.bool(false)
local seeds = imgui.new.bool(false)
local drags = imgui.new.bool(false)

local pool = {
    seeds = {},
    drags = {}
}

local seeds_sprite = 45
local drags_sprite = 56

function main()
    while not isSampAvailable() do
        wait(100)
    end

    sampAddChatMessage('>> {31B404}{GhettoMAP} {FFFFFF}Open: /map <<', -1)

    sampRegisterChatCommand('map', function()
        state[0] = not state[0]
    end)

    while true do
        wait(0)

        if seeds[0] then
            add(seeds_coords, pool.seeds, seeds_sprite)
        else
            remove(pool.seeds)
        end

        if drags[0] then
            add(drags_coords, pool.drags, drags_sprite)
        else
            remove(pool.drags)
        end
    end
end

function add(coords, pool, sprite)
    for i, pos in ipairs(coords) do
        if pool[i] == nil then
            pool[i] = addSpriteBlipForCoord(
                pos[1],
                pos[2],
                pos[3],
                sprite
            )
        end
    end
end

function remove(pool)
    for i, blip in pairs(pool) do
        if blip ~= nil then
            removeBlip(blip)
            pool[i] = nil
        end
    end
end

imgui.OnFrame(
    function()
        return state[0]
    end,
    function()
        imgui.SetNextWindowSize(
            imgui.ImVec2(350, 180),
            imgui.Cond.FirstUseEver
        )

        imgui.Begin(
            'GhettoMAP',
            state,
            imgui.WindowFlags.NoResize
        )

        imgui.Text('Метки карты')
        imgui.Separator()

        imgui.Checkbox('Показывать семки', seeds)
        imgui.Checkbox('Показывать закладки', drags)

        imgui.Spacing()
        imgui.Separator()
        imgui.Text('GhettoMAP')

        imgui.End()
    end
)

function onScriptTerminate(script)
    if script == thisScript() then
        remove(pool.seeds)
        remove(pool.drags)
    end
end

